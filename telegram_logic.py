def _webhook_base_url() -> str | None:
    """Public HTTPS base URL for Telegram webhooks (Render sets RENDER_EXTERNAL_URL)."""
    for key in ("WEBHOOK_URL", "RENDER_EXTERNAL_URL"):
        value = (os.environ.get(key) or "").rstrip("/")
        if value:
            return value
    return None


if __name__ == "__main__":
    print("Starting bot...")
    app = Application.builder().token(TOKEN).build()

    set_date_conv = ConversationHandler(
        entry_points=[CommandHandler("set_date", set_date_command)],
        states={
            ASK_DATE: [MessageHandler(filters.TEXT & ~filters.COMMAND, receive_date)],
        },
        fallbacks=[CommandHandler("cancel", cancel_conversation)],
    )

    check_parade_conv = ConversationHandler(
        entry_points=[CommandHandler("check_parade_state", check_parade_state_command)],
        states={
            ASK_PARADE_STATE: [
                MessageHandler(filters.TEXT & ~filters.COMMAND, receive_parade_state)
            ],
        },
        fallbacks=[CommandHandler("cancel", cancel_conversation)],
    )

    # Cold-start notice runs before other handlers
    app.add_handler(TypeHandler(Update, notify_cold_start), group=-1)

    # commands
    app.add_handler(CommandHandler("start", start_command))
    app.add_handler(CommandHandler("summarise", summarise_command))
    app.add_handler(CommandHandler("check_date", check_date_command))
    app.add_handler(CommandHandler("wbgt_cat_haze", wbgt_cat_haze_command))
    app.add_handler(set_date_conv)
    app.add_handler(check_parade_conv)

    # messages (after ConversationHandlers so date/parade replies are captured first)
    app.add_handler(MessageHandler(filters.TEXT & ~filters.COMMAND, handle_message))

    # errors
    app.add_error_handler(error)

    base_url = _webhook_base_url()
    if base_url:
        port = int(os.environ.get("PORT", "8443"))
        webhook_url = f"{base_url}/{WEBHOOK_PATH}"
        print(f"Webhook mode → {webhook_url} (port {port})")
        app.run_webhook(
            listen="0.0.0.0",
            port=port,
            url_path=WEBHOOK_PATH,
            webhook_url=webhook_url,
            drop_pending_updates=True,
        )
    else:
        # Local/dev without a public URL: fall back to polling
        print("No WEBHOOK_URL/RENDER_EXTERNAL_URL set — polling for local use.")
        print("Polling...")
        app.run_polling(poll_interval=3)
